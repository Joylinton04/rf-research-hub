import type { CollectionConfig } from 'payload';

// Every uploaded file in the site lives here. `upload` turns the collection into
// Payload's file-handling type: the admin panel renders a drag-and-drop field
// instead of a text input, and each row stores the filename, MIME type and
// dimensions alongside whatever metadata is declared below.
//
// Bytes do not go to disk. `s3Storage` in payload.config.ts points the adapter
// at the Neon "media" bucket, so local storage is disabled and every derivative
// below is PUT to the bucket on save.
export const Media: CollectionConfig = {
  slug: 'media',
  labels: {
    singular: 'Media',
    plural: 'Media',
  },
  admin: {
    useAsTitle: 'filename',
    defaultColumns: ['filename', 'alt', 'updatedAt'],
    description:
      'Images used across the site. Upload once here, then pick the file from a Researcher or Project.',
  },
  access: {
    // Files are served through Payload's own route, which runs this check on
    // every request — so `read` has to stay public or the images 403 for
    // visitors. Only signed-in admins can add or remove them.
    read: () => true,
    create: ({ req }) => Boolean(req.user),
    update: ({ req }) => Boolean(req.user),
    delete: ({ req }) => Boolean(req.user),
  },
  upload: {
    // Rejects non-images in the admin panel before the upload starts.
    mimeTypes: ['image/*'],
    // Generated by sharp on save and stored as separate objects, so next/image
    // is never handed a 676KB original to downscale at request time.
    //
    // Width only, no height: the sizes scale proportionally and never crop.
    // This collection holds both square portraits and landscape project
    // thumbnails, and a fixed-ratio crop would have to discard the sides of one
    // or the other. The cards already carry `object-cover`, so framing is a
    // layout concern and the stored file keeps every pixel.
    imageSizes: [
      { name: 'thumbnail', width: 400 },
      { name: 'card', width: 768 },
      // The widest any image is rendered — TeamLeaderCard's portrait column on
      // a 2x display.
      { name: 'feature', width: 1280 },
    ],
    adminThumbnail: 'thumbnail',
  },
  fields: [
    {
      name: 'alt',
      type: 'text',
      required: true,
      admin: {
        description:
          'Describes the image for screen readers and for when it fails to load. For a portrait, the person’s name is the right answer.',
      },
    },
    {
      name: 'credit',
      type: 'text',
      admin: {
        description: 'Optional photographer or source attribution.',
      },
    },
  ],
};
